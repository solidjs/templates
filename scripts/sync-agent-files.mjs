#!/usr/bin/env node
// Generates the AGENTS.md of every `solid-v2` template from one source,
// agents/solid-2.0-primer.md: the managed block, then the template's own text.
// One file: Codex, Cursor, Copilot and Gemini CLI read a root AGENTS.md, and
// Claude Code falls back to it when there is no CLAUDE.md.
//
// The managed block is delimited by `<!-- BEGIN solid-2.0-primer -->` /
// `<!-- END solid-2.0-primer -->`; re-running replaces only that block and
// keeps whatever a template adds outside it. Plain Node, no dependencies.
//
//   node scripts/sync-agent-files.mjs          write
//   node scripts/sync-agent-files.mjs --check  exit 1 if anything is stale
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const check = process.argv.includes('--check');

const BEGIN = '<!-- BEGIN solid-2.0-primer -->';
const END = '<!-- END solid-2.0-primer -->';
const NOTE =
  '<!-- Generated by scripts/sync-agent-files.mjs from agents/solid-2.0-primer.md. Edit the primer and re-run; edits inside this block are overwritten. -->';

const primer = readFileSync(
  join(root, 'agents', 'solid-2.0-primer.md'),
  'utf8',
).trim();
const block = `${BEGIN}\n${NOTE}\n\n${primer}\n\n${END}`;

// The hand-written sections every template used to carry verbatim; the
// primer's "Where to look" section covers them now, so a legacy AGENTS.md
// (no managed block yet) drops them and keeps only its template-specific text.
const LEGACY_PREAMBLE = /^# Agent Guide\s*\n/;
const LEGACY_SECTIONS = [
  /^## Versioned skills\b/,
  /^## Reactive diagnostics\b/,
];

/** Names of the solid-v2 templates: templates.json first, the directory as fallback. */
function templateNames() {
  const groupDir = 'solid-v2';
  try {
    const manifest = JSON.parse(
      readFileSync(join(root, 'templates.json'), 'utf8'),
    );
    const group = Object.values(manifest.groups).find(
      (g) => g.path === groupDir,
    );
    if (group) return { groupDir, names: group.templates.map((t) => t.name) };
  } catch {
    // fall through to the directory listing
  }
  const names = readdirSync(join(root, groupDir), { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();
  return { groupDir, names };
}

/** Replaces the managed block in `text`, or returns null when there is none. */
function replaceBlock(text) {
  const start = text.indexOf(BEGIN);
  const end = text.indexOf(END);
  if (start === -1 || end === -1 || end < start) return null;
  return text.slice(0, start) + block + text.slice(end + END.length);
}

/** What a legacy AGENTS.md says about its own stack, with the shared sections removed. */
function templateSpecificText(text) {
  const body = text.replace(LEGACY_PREAMBLE, '');
  // Split into sections at `## ` headings; the chunk before the first heading
  // is the legacy intro paragraph when the preamble matched.
  const parts = body.split(/^(?=## )/m);
  const kept = parts.filter((part, i) => {
    if (i === 0 && !part.startsWith('## ')) return !LEGACY_PREAMBLE.test(text);
    return !LEGACY_SECTIONS.some((re) => re.test(part));
  });
  return kept.join('').trim();
}

function agentsMd(existing) {
  if (existing !== null) {
    const replaced = replaceBlock(existing);
    if (replaced !== null) return replaced;
    const rest = templateSpecificText(existing);
    return rest ? `${block}\n\n${rest}\n` : `${block}\n`;
  }
  return `${block}\n`;
}

function read(path) {
  return existsSync(path) ? readFileSync(path, 'utf8') : null;
}

let stale = 0;
let written = 0;
const { groupDir, names } = templateNames();
for (const name of names) {
  const dir = join(root, groupDir, name);
  if (!existsSync(dir)) {
    console.warn(`skip ${groupDir}/${name}: directory does not exist`);
    continue;
  }
  const path = join(dir, 'AGENTS.md');
  const existing = read(path);
  const next = agentsMd(existing);
  if (existing === next) continue;
  stale++;
  if (check) {
    console.log(`stale: ${relative(root, path)}`);
    continue;
  }
  writeFileSync(path, next);
  written++;
  console.log(`wrote ${relative(root, path)}`);
}

if (check) {
  if (stale > 0) {
    console.error(
      `${stale} agent file(s) out of date; run: node scripts/sync-agent-files.mjs`,
    );
    process.exit(1);
  }
  console.log(`agent files up to date across ${names.length} templates`);
} else {
  console.log(`${written} file(s) written across ${names.length} templates`);
}
